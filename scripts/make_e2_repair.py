#!/usr/bin/env python3
"""Draft an E2 repair request: re-run failed or lost items of fetched E2 requests under the same ids (S024, T-015).

    python scripts/make_e2_repair.py <rid> [<rid> ...] --id 017-e2-repair01 [--target-h 2.5] [--write]

Reads results/cce/<rid>/{request.yaml, merged.jsonl}. An item is repaired when its record is missing (lost or
timed-out shard) or not ok. The item dicts (id, host, cif, item protocol with direction, window prior and
configuration chunk, pred_h) are copied unchanged, so the re-run uses the same seeds; only `shard` is reassigned
by first-fit decreasing packing (scripts/make_e2_request.py `pack`). The top-level protocol must be the same in all
source requests and is copied. qkhosts.labels.assemble lets an item id in a later request supersede the earlier one,
so `assemble_e2_labels.py <rids...> <repair id>` gives the repaired labels. --write puts the draft in
compute/drafts/<id>.yaml and the plan in results/T-015/<UTC>_<sha>/.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from make_e2_request import makespan, pack, request_yaml  # noqa: E402
from qkhosts.labels.assemble import read_records  # noqa: E402


def repair_items(req: dict, records: list[dict]) -> tuple[list[dict], dict]:
    """Items of `req` whose record is missing or not ok, and the reason per item id."""
    recs = {r.get("id"): r for r in records}
    out, why = [], {}
    for it in req["materials"]:
        r = recs.get(it["id"])
        if r is None:
            why[it["id"]] = "no record"
        elif not r.get("ok"):
            why[it["id"]] = str(r.get("error", "not ok")).splitlines()[0][:120]
        else:
            continue
        out.append(dict(it))
    return out, why


def build_repair(sources: list[tuple[dict, list[dict]]], target_h: float) -> dict:
    """{protocol, items (shard reassigned), loads, why, sources} from (request, records) pairs."""
    protos = [json.dumps(q["protocol"], sort_keys=True) for q, _ in sources]
    if len(set(protos)) != 1:
        raise ValueError("source requests differ in top-level protocol; repair them separately")
    items, why = [], {}
    for q, recs in sources:
        its, w = repair_items(q, recs)
        items += its
        why.update({f"{q['id']}/{k}": v for k, v in w.items()})
    if not items:
        return {"protocol": sources[0][0]["protocol"], "items": [], "loads": [], "why": why}
    bins = pack([it["pred_h"] for it in items], target_h)
    for s, b in enumerate(bins):
        for i in b:
            items[i]["shard"] = s
    loads = [sum(items[i]["pred_h"] for i in b) for b in bins]
    return {"protocol": sources[0][0]["protocol"], "items": sorted(items, key=lambda it: (it["shard"], it["id"])),
            "loads": loads, "why": why, "hosts": sorted({it["host"] for it in items})}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("rids", nargs="+")
    ap.add_argument("--id", required=True, help="repair request id, e.g. 017-e2-repair01")
    ap.add_argument("--target-h", type=float, default=2.5)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    started = dt.datetime.now(dt.timezone.utc)
    sources = []
    for rid in a.rids:
        d = ROOT / "results" / "cce" / rid
        q = yaml.safe_load((d / "request.yaml").read_text(encoding="utf-8"))
        recs = read_records(d)
        sources.append((q, recs))
    rep = build_repair(sources, a.target_h)
    summary = {"id": a.id, "sources": a.rids, "hosts": len(rep.get("hosts", [])), "items": len(rep["items"]),
               "shards": len(rep["loads"]), "runner_h_pred": round(sum(rep["loads"]), 2),
               "max_shard_h": round(max(rep["loads"]), 2) if rep["loads"] else 0.0,
               "wall_h_at_20": round(makespan(rep["loads"]), 2), "why": rep["why"]}
    print(json.dumps(summary, indent=1))
    if not a.write or not rep["items"]:
        return 0
    from qkhosts.run import env_text, git_state, make_run_dir
    sha, dirty = git_state()
    ended = dt.datetime.now(dt.timezone.utc)
    out = make_run_dir(ROOT / "results", "T-015", sha, dirty, ended)
    header = [f"DRAFT (T-015 repair, S024). {a.id}: re-runs {len(rep['items'])} failed or lost items of "
              f"{', '.join(a.rids)} under the same ids ({summary['hosts']} hosts, {summary['shards']} shards).",
              f"Generated by scripts/make_e2_repair.py ({started:%Y-%m-%d %H:%M} UTC); plan: {out.relative_to(ROOT).as_posix()}/",
              f"Predicted: {summary['runner_h_pred']} runner-h, max shard {summary['max_shard_h']} h, about "
              f"{summary['wall_h_at_20']} h wall at 20 jobs. Item dicts copied unchanged (same seeds); shards repacked.",
              "Labels: scripts/assemble_e2_labels.py <sources...> <this id> (later item ids supersede earlier ones).",
              "Launch = git mv to compute/requests/ with Kian's OK, one request per push."]
    req = {"items": rep["items"], "loads": rep["loads"]}
    (ROOT / "compute" / "drafts" / f"{a.id}.yaml").write_text(request_yaml(a.id, rep["protocol"], req, header),
                                                              encoding="utf-8", newline="\n")
    (out / "metrics.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    (out / "env.txt").write_text(env_text(sha, dirty, sys.argv, started, ended), encoding="utf-8")
    print(f"-> {out} and compute/drafts/{a.id}.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
